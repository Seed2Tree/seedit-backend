-- ====================================================================
-- 3. 과거 1300 영업일(약 5년) 히스토리 (차트용)
--
--    rn=1   : 어제
--    rn=260 : 약 1년 전 (영업일 기준)
--    rn=1300: 약 5년 전
--
--    trend > 0 → 과거로 갈수록 가격 높음 (현재까지 하락한 종목)
--    trend < 0 → 과거로 갈수록 가격 낮음 (현재까지 상승한 종목)
--    ※ trend는 5년(1300일) 누적 드리프트가 ±35% 이내가 되도록 설정
--      (값을 키우면 과거 가격이 음수가 될 수 있음)
--    장주기 SIN(rn*0.009) 항: 주기 약 2.8년의 큰 흐름 → 1년/5년 차트 구분
--
--    종목별 설정 (sp):
--      sid | base   | amp  | trend     | phase | w52h   | w52l   | avg_vol
--       1  | 71300  | 0.20 | +0.00020  | 0.0   | 87500  | 53700  | 12480000  (삼성전자, 하락)
--       2  | 218500 | 0.22 | -0.00027  | 1.1   | 260000 | 130000 |  3200000  (SK하이닉스, 상승)
--       3  | 196400 | 0.14 | -0.00013  | 2.2   | 230000 | 160000 |   820000  (NAVER, 소폭상승)
--       4  |  38750 | 0.20 | +0.00027  | 0.5   |  55000 |  30000 |  2100000  (카카오, 하락)
--       5  | 922000 | 0.11 | -0.00015  | 3.1   |1000000 | 750000 |   180000  (삼성바이오, 소폭상승)
--       6  | 412500 | 0.16 | +0.00022  | 1.8   | 500000 | 350000 |   540000  (LG에너지, 하락)
--       7  | 248000 | 0.14 | -0.00020  | 2.7   | 290000 | 200000 |   980000  (현대차, 상승)
--       8  | 115000 | 0.16 | -0.00025  | 0.9   | 130000 |  90000 |  1350000  (기아, 상승)
--       9  | 320000 | 0.13 | +0.00015  | 1.4   | 380000 | 280000 |   430000  (LG화학, 하락)
--      10  | 340000 | 0.15 | -0.00010  | 2.0   | 400000 | 280000 |   310000  (포스코, 소폭상승)
-- ====================================================================
-- 1300 영업일 ≈ 달력일 1900일 재귀 필요 (MySQL 기본 한도 1000 → 상향)
SET SESSION cte_max_recursion_depth = 2200;

INSERT IGNORE INTO stock_detail
    (sid, trade_date,
     open_price, close_price, current_price, high_price, low_price,
     prev_close_price, volume, trading_value,
     w52_high_price, w52_low_price)
WITH RECURSIVE n AS (
    SELECT 1 AS i
    UNION ALL
    SELECT i + 1 FROM n WHERE i < 1900
),
td AS (
    SELECT
        ROW_NUMBER() OVER (ORDER BY i) AS rn,
        CURDATE() - INTERVAL i DAY     AS d
    FROM n
    WHERE DAYOFWEEK(CURDATE() - INTERVAL i DAY) NOT IN (1, 7)
),
sp (sid, base, amp, trend, ph, w52h, w52l, avg_vol) AS (
    SELECT 1,  71300,  0.20,  0.00020, 0.0,  87500,  53700, 12480000 UNION ALL
    SELECT 2, 218500,  0.22, -0.00027, 1.1, 260000, 130000,  3200000 UNION ALL
    SELECT 3, 196400,  0.14, -0.00013, 2.2, 230000, 160000,   820000 UNION ALL
    SELECT 4,  38750,  0.20,  0.00027, 0.5,  55000,  30000,  2100000 UNION ALL
    SELECT 5, 922000,  0.11, -0.00015, 3.1,1000000, 750000,   180000 UNION ALL
    SELECT 6, 412500,  0.16,  0.00022, 1.8, 500000, 350000,   540000 UNION ALL
    SELECT 7, 248000,  0.14, -0.00020, 2.7, 290000, 200000,   980000 UNION ALL
    SELECT 8, 115000,  0.16, -0.00025, 0.9, 130000,  90000,  1350000 UNION ALL
    SELECT 9, 320000,  0.13,  0.00015, 1.4, 380000, 280000,   430000 UNION ALL
    SELECT 10,340000,  0.15, -0.00010, 2.0, 400000, 280000,   310000
),
prices AS (
    SELECT
        sp.sid,
        td.d,
        td.rn,
        -- 시가 (장주기 + 중기 + 단기 파동 + 추세)
        ROUND(sp.base * (1 + sp.amp * 0.5 * SIN(td.rn * 0.009 + sp.ph * 1.7)
            + sp.amp * SIN(td.rn * 0.047 + sp.ph)
            + sp.amp * 0.35 * COS(td.rn * 0.19 + sp.ph + 0.8)
            + sp.trend * td.rn), -2)  AS op,
        -- 종가 (시가와 위상 살짝 다르게 → 음봉/양봉 자연스럽게)
        ROUND(sp.base * (1 + sp.amp * 0.5 * SIN(td.rn * 0.009 + sp.ph * 1.7)
            + sp.amp * SIN(td.rn * 0.047 + sp.ph + 0.17)
            + sp.amp * 0.35 * COS(td.rn * 0.19 + sp.ph + 0.95)
            + sp.trend * td.rn), -2)  AS cp,
        -- 장중 등락폭 (고가-저가 범위)
        ROUND(sp.base * 0.011, -2)   AS intra,
        -- 거래량
        ROUND(sp.avg_vol * (0.45 + 0.9 * ABS(SIN(td.rn * 0.31 + sp.ph)))) AS vol,
        sp.w52h,
        sp.w52l,
        sp.base,
        sp.amp,
        sp.trend,
        sp.ph
    FROM td
    CROSS JOIN sp
    WHERE td.rn <= 1300
)
SELECT
    sid,
    d                                                    AS trade_date,
    op                                                   AS open_price,
    cp                                                   AS close_price,
    cp                                                   AS current_price,
    ROUND(GREATEST(op, cp) + intra, -2)                  AS high_price,
    GREATEST(ROUND(LEAST(op, cp) - intra, -2), 100)     AS low_price,    -- 최소 100원 보장
    -- 전일 종가 = 다음 날(rn+1) close 근사값
    ROUND(base * (1 + amp * 0.5 * SIN((rn + 1) * 0.009 + ph * 1.7)
        + amp * SIN((rn + 1) * 0.047 + ph + 0.17)
        + amp * 0.35 * COS((rn + 1) * 0.19 + ph + 0.95)
        + trend * (rn + 1)), -2)                         AS prev_close_price,
    vol                                                  AS volume,
    cp * vol                                             AS trading_value,
    w52h                                                 AS w52_high_price,
    w52l                                                 AS w52_low_price
FROM prices;
